document.addEventListener('DOMContentLoaded', () => {
    const featuredView = document.getElementById('featured-view');
    const archiveView = document.getElementById('archive-view');
    const detailView = document.getElementById('detail-view');
    const detailContainer = document.querySelector('.detail-container');
    const backBtn = document.getElementById('back-btn');
    const projectItems = document.querySelectorAll('.project-item');
    const navItems = document.querySelectorAll('.nav-item');
    const navLinks = document.querySelectorAll('.nav-item a');

    let currentContext = 'featured'; // 'featured' or 'archive'

    // Navigation Handling
    navLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const view = link.getAttribute('data-view');

            if (view === 'featured') {
                switchView('featured');
            } else if (view === 'archive') {
                switchView('archive');
            } else if (view === 'about') {
                switchView('about');
            }
        });
    });

    function switchView(viewName) {
        // Update Nav State
        navItems.forEach(item => item.classList.remove('active'));
        document.querySelector(`.nav-item a[data-view="${viewName}"]`).parentElement.classList.add('active');

        // Hide Detail View if open
        if (document.body.classList.contains('detail-mode')) {
            closeDetailView();
        }

        // Toggle Views
        const views = ['featured', 'archive', 'about'];
        views.forEach(v => {
            const viewEl = document.getElementById(`${v}-view`);
            if (v === viewName) {
                viewEl.classList.remove('hidden');
                currentContext = v;
            } else {
                viewEl.classList.add('hidden');
            }
        });

        // Scroll to top
        window.scrollTo(0, 0);
    }

    // Accordion Logic
    const accordionHeaders = document.querySelectorAll('.accordion-header');

    accordionHeaders.forEach(header => {
        header.addEventListener('click', () => {
            const item = header.parentElement;
            const isActive = item.classList.contains('active');

            // Close all other items (optional - if we want only one open at a time)
            // For this request, we'll keep it simple or allow multiple? 
            // "Click to expand" usually implies toggle. 
            // Let's implement independent toggling for better UX in this profile context.

            // Toggle current
            if (isActive) {
                item.classList.remove('active');
            } else {
                item.classList.add('active');
            }
        });
    });

    // Handle Project Item Click (Delegation for potentially dynamic items)
    // Existing project items are static, but we can iterate them.
    // We also need to handle Archive items.

    // Re-select all project items (including archive ones)
    const allProjectItems = document.querySelectorAll('.project-item');

    allProjectItems.forEach(item => {
        item.addEventListener('click', () => {
            const projectId = item.getAttribute('data-id');
            // Check if it's an archive project or featured project
            // For this demo, we assume we might need data for archive too.
            // If data is missing, we might use placeholders or extended data.

            // Let's extend projectData or just use what we have.
            // Archive items have data-id="archive1", etc.
            // We need to add these to projectData or handle them.

            let data = projectData[projectId];

            if (data) {
                // Populate Detail View
                renderDetail(data);

                // Switch View
                featuredView.classList.add('hidden');
                archiveView.classList.add('hidden'); // Hide archive too
                detailView.classList.remove('hidden');
                document.body.classList.add('detail-mode'); // Add detail mode class
                window.scrollTo(0, 0); // Scroll to top
            }
        });
    });

    // Handle Back Button Click
    backBtn.addEventListener('click', () => {
        closeDetailView();
    });

    function closeDetailView() {
        detailView.classList.add('hidden');
        document.body.classList.remove('detail-mode'); // Remove detail mode class

        // Restore previous context
        if (currentContext === 'featured') {
            featuredView.classList.remove('hidden');
            archiveView.classList.add('hidden');
        } else {
            featuredView.classList.add('hidden');
            archiveView.classList.remove('hidden');
        }
        window.scrollTo(0, 0);
    }

    // Render Detail Content
    // Render Detail Content
    function renderDetail(data) {
        // Clear previous content
        detailContainer.innerHTML = '';

        let toolsHtml = '';
        if (!data.fullWidthTools) {
            toolsHtml = `<p><strong>Tools:</strong> ${data.tools}</p>`;
        }

        // Header Section
        const headerHTML = `
            <div class="detail-header">
                <h1 class="detail-title">${data.title}</h1>
                <div class="detail-info">
                    <p><strong>Period:</strong> ${data.period}</p>
                    ${data.role ? `<p><strong>Role:</strong> ${data.role}</p>` : ''}
                    ${data.format ? `<p><strong>Format:</strong> ${data.format}</p>` : ''}
                    <p><strong>Work Scope:</strong> ${data.scope}</p>
                    ${toolsHtml}
                </div>
                ${data.fullWidthTools ? `<div class="detail-full-width" style="margin-top: 1rem; color: #AAAAAA;"><p><strong>Tools:</strong> ${data.tools}</p></div>` : ''}
                <p style="margin-top: 1rem; font-weight: 300;">${data.description}</p>
            </div>
        `;

        // Images Section Container
        let imagesHTML = '<div class="detail-images">';

        // 1. Render Top Videos (if any) - Positioned BEFORE images
        if (data.videosTop && data.videosTop.length > 0) {
            imagesHTML += '<div class="detail-videos">';
            data.videosTop.forEach(videoSrc => {
                imagesHTML += `
                    <div class="video-wrapper">
                        <!-- Fluid Width Video with Max Constraint -->
                        <video autoplay loop muted playsinline>
                            <source src="${videoSrc}" type="video/mp4">
                            Your browser does not support the video tag.
                        </video>
                    </div>
                `;
            });
            imagesHTML += '</div>';
        }

        // 2. Render Mixed Content (Images & Videos in sequence)
        if (data.images && data.images.length > 0) {
            data.images.forEach(mediaSrc => {
                if (mediaSrc.endsWith('.mp4')) {
                    // Render Video within Images List
                    imagesHTML += `
                        <div class="video-wrapper">
                            <!-- Fluid Width Video with Max Constraint -->
                            <video autoplay loop muted playsinline>
                                <source src="${mediaSrc}" type="video/mp4">
                                Your browser does not support the video tag.
                            </video>
                        </div>
                    `;
                } else {
                    // Render Image
                    imagesHTML += `<img src="${mediaSrc}" alt="${data.title} Image">`;
                }
            });
        }

        // 3. Render Bottom Videos (if any) - Positioned AFTER images
        // Supports legacy 'videos' property as bottom videos for compatibility
        const bottomVideos = data.videosBottom || data.videos;
        if (bottomVideos && bottomVideos.length > 0) {
            imagesHTML += '<div class="detail-videos">';
            bottomVideos.forEach(videoSrc => {
                imagesHTML += `
                    <div class="video-wrapper">
                        <!-- Fluid Width Video with Max Constraint -->
                        <video autoplay loop muted playsinline>
                            <source src="${videoSrc}" type="video/mp4">
                            Your browser does not support the video tag.
                        </video>
                    </div>
                `;
            });
            imagesHTML += '</div>';
        }

        imagesHTML += '</div>';

        // Inject HTML
        detailContainer.innerHTML = headerHTML + imagesHTML;
    }
});
